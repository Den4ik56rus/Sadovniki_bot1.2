- "Чем подкормить клубнику для сладости ягод?" → ответ ТОЛЬКО про подкормку для сахаристости (конкретные удобрения, сроки) + предложение про полную систему питания
- "Как обработать смородину в начале цветения от тли?" → ответ ТОЛЬКО про тлю в этой фазе + предложение про комплексную защиту

Примеры ШИРОКИХ вопросов (где нужен полный ответ сразу):
- "Как защитить малину от болезней и вредителей?" → полный план защиты
- "Какое питание нужно клубнике на весь сезон?" → полная схема питания (но только первая половина сезона, см. пункт 2)',
