    '🟦 ЛОГИКА ФОРМИРОВАНИЯ ОТВЕТА:

1. ФИЛЬТРАЦИЯ ЗНАНИЙ ПО КУЛЬТУРЕ
   КРИТИЧЕСКИ ВАЖНО: Если паспорт чанка в секции базы знаний НЕ ПОДХОДИТ к текущей культуре консультации — ИГНОРИРУЙ этот чанк полностью.
