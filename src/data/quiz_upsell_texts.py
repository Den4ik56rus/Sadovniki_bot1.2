def get_upsell_trigger_text(problem_key: str) -> str:
    """Возвращает текст-триггер upsell-опроса по problem_key.

    Если для ключа нет уникального текста — формирует универсальный
    на основе названия культуры и проблемы из funnel_b_problems.
    """
    text = _UPSELL_TEXTS.get(problem_key)
    if text:
        return text

    # Fallback: универсальный шаблон
    info = _ALL_PROBLEMS_MAP.get(problem_key)
    if info:
        culture_label = get_culture_label(info["culture_key"], info.get("variety_key"))
        problem_label = info["label"].lower()
    else:
        culture_label = "вашей культуры"
        problem_label = "вашей проблемы"

    return (
        f"Чёткий план решения проблемы «{problem_label}» по {culture_label.lower()} уже у вас.\n\n"
        "Чтобы я мог сказать, хватит ли разового плана или нужен системный подход — "
        "ответьте на три коротких вопроса. 30 секунд."
    )
