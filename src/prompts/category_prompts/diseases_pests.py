# src/prompts/category_prompts/diseases_pests.py

"""
Специфичный промпт для категории "Защита от болезней и вредителей".
"""

from typing import Tuple
from ._fertilizers_reference import get_pesticides_reference


def get_diseases_pests_category_prompt(
    culture: str,
    default_location: str = "средняя полоса",
    default_growing_type: str = "открытый грунт"
) -> Tuple[str, bool]:
    """
    Возвращает специфичные инструкции для консультаций по защите растений.

    Args:
        culture: Название культуры (например, "малина", "голубика", "клубника ремонтантная")
        default_location: Местоположение по умолчанию
        default_growing_type: Тип выращивания по умолчанию

    Returns:
        Tuple[str, bool]:
            - str: Строка с инструкциями для LLM по категории "защита растений"
            - bool: use_minimal_base (False = использовать полный базовый промпт)
    """
    pesticides_ref = get_pesticides_reference()

    prompt = f"""
🟦 **ТЕХНИЧЕСКИЙ ШАБЛОН ДЛЯ ИИ
"СИСТЕМА ЗАЩИТЫ ЯГОДНЫХ КУЛЬТУР"**
(клубника, малина, ежевика, смородина, крыжовник, жимолость, голубика)

Текущая культура: {culture}

Все препараты, сроки ожидания, нормы и кратность — ИИ подставляет из базы и справочника ниже.

🟦 1. Введение
ИИ объясняет:
— цель защитной схемы — профилактика, а не лечение;
— химия возможна до вегетации / до цветения и после сбора урожая;
— во время плодоношения — ничего или только био;
— схема учитывает типичные вредители и болезни культуры.

🟦 2. Группы препаратов
ИИ должен коротко объяснить:

🟦 Фунгициды (контактные и системные)
— от грибковых болезней;
— контактные — весной, системные — после плодоношения.

🟦 Инсектициды
— против насекомых-вредителей (тля, долгоносик, трипсы и др.).

🟦 Акарициды
— против клещей (паутинный, земляничный, почковый и т.д.).

🟦 Инсектоакарициды
— универсальная группа, когда вредитель не установлен.

🟦 Биопрепараты
— можно применять в период плодоношения.

ИИ определяет группу, а конкретный препарат загружает из базы.

🟦 3. Основная схема защитных обработок
ИИ должен использовать следующий хронологический план, подставляя препараты из базы:

🟦 1. Ранняя весна — до начала вегетации
Фунгицид на основе меди (контактный)
Цель: уничтожение зимующих грибковых инфекций.
ИИ подставляет: препарат, защитное действие, нормы, срок ожидания.

🟦 2. Фаза 3–4 настоящих листьев
Инсектицид (химический)
Цель: профилактика тли, долгоносика, трипсов и других вредителей, активных в начале сезона.

🟦 3. Через 10–14 дней после инсектицида
Акарицид (химический)
Цель: остановить развитие клещей, которые часто незаметны на ранних стадиях.
ИИ подставляет срок ожидания и кратность.

🟦 4. Период цветения и плодоношения
Ничего или биопрепараты (по необходимости)
— химия запрещена;
— био разрешено (ИИ подставляет из базы).
Пример логики: клубника — био от трипсов; жимолость — редко требуется, т.к. сбор ранний.

🟦 5. После сбора урожая
🟦 Системный фунгицид
— восстановление растения;
— защита от пятнистостей и гнилей, которые уходят зимовать.

🟦 Инсектоакарицид (или пара: инсектицид + акарицид)
— уничтожение вредителей, уходящих на зимовку;
— профилактика повторного вселения.

ИИ подставляет:
— подходящий препарат или комбинацию;
— кратность;
— срок ожидания.

🟦 4. Культура-специфические акценты
ИИ обязан учитывать особенности:

🟦 Клубника — риск долгоносика, земляничного клеща, серой гнили → упор на раннюю химию и пост-урожайную обработку.

🟦 Малина — вредители побегов (муха, галлица), клещи → акцент на инсектициде в фазе роста побегов и акарициде.

🟦 Ежевика — высокая чувствительность к клещам → акарицидные обработки обязательны.

🟦 Смородина/крыжовник — тля, стеклянница, антракноз → инсектицид весной, затем акарицид.

🟦 Жимолость — очень раннее цветение → химия только до начала вегетации; далее в сезон — только био.

🟦 Голубика — упор на фунгициды (гниль, пятнистости) и профилактику почвенных патогенов.

🟦 5. Требования к ответу ИИ
ИИ всегда должен:
🟦 подставлять препараты только из базы
🟦 проверять, есть ли плодоношение (если да → только био)
🟦 указывать срок ожидания
🟦 указывать защитное действие
🟦 указывать кратность и интервал обработок
🟦 учитывать специфику растения
🟦 использовать понятные формулировки без лишней химии

{pesticides_ref}
""".strip()

    return (prompt, False)  # False = использовать полный базовый промпт
