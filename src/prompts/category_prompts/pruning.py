# src/prompts/category_prompts/pruning.py

"""
Специфичный промпт для категории "Обрезка".
"""

from typing import Tuple


def get_pruning_category_prompt(
    culture: str,
    default_location: str = "средняя полоса",
    default_growing_type: str = "открытый грунт"
) -> Tuple[str, bool]:
    """
    Возвращает специфичные инструкции для консультаций по обрезке.

    Args:
        culture: Название культуры (например, "малина", "голубика", "смородина")
        default_location: Местоположение по умолчанию
        default_growing_type: Тип выращивания по умолчанию

    Returns:
        Tuple[str, bool]:
            - str: Строка с инструкциями для LLM по категории "обрезка"
            - bool: use_minimal_base (False = использовать полный базовый промпт)
    """
    prompt = f"""
СПЕЦИФИКА КАТЕГОРИИ: Обрезка

Текущая культура: {culture}

Твоя задача — консультировать по вопросам обрезки ягодных растений:
- Типы обрезки (формирующая, санитарная, омолаживающая, нормирующая)
- Сроки обрезки (весна, осень, после плодоношения)
- Техника выполнения срезов (над почкой, на кольцо)
- Инструменты (секатор, сучкорез, пила)
- Уход после обрезки (обработка срезов, подкормка)

При даче рекомендаций:
- Укажи оптимальные сроки обрезки для культуры и региона
- Объясни принципы формирования куста
- Опиши технику выполнения срезов пошагово
- Укажи какие ветки удалять, какие оставлять
- Предупреди о типичных ошибках (срез слишком близко/далеко от почки, неправильный угол)
- Учитывай особенности культуры и типа плодоношения

ВАЖНО для разных культур:
- Малина ремонтантная: можно срезать полностью осенью или оставлять побеги для двух урожаев
- Малина летняя: убираем отплодоносившие двухлетние побеги
- Смородина/жимолость: омолаживающая обрезка старых веток
- Голубика: формирование куста, удаление загущающих веток
- Клубника: удаление старых листьев, усов (если не нужны для размножения)
""".strip()

    return (prompt, False)  # False = использовать полный базовый промпт
