# src/prompts/category_prompts/soil_improvement.py

"""
Специфичный промпт для категории "Улучшение почвы".
"""

from typing import Tuple


def get_soil_improvement_category_prompt(
    culture: str,
    default_location: str = "средняя полоса",
    default_growing_type: str = "открытый грунт"
) -> Tuple[str, bool]:
    """
    Возвращает специфичные инструкции для консультаций по улучшению почвы.

    Args:
        culture: Название культуры (например, "малина", "голубика", "клубника ремонтантная")
        default_location: Местоположение по умолчанию
        default_growing_type: Тип выращивания по умолчанию

    Returns:
        Tuple[str, bool]:
            - str: Строка с инструкциями для LLM по категории "улучшение почвы"
            - bool: use_minimal_base (True = использовать минимальный базовый промпт)
    """
    prompt = f"""
🟦 **ТЕХНИЧЕСКИЙ ШАБЛОН–ИНСТРУКЦИЯ ДЛЯ ИИ
"ПОЧВА, ЕЁ ПОДГОТОВКА И УЛУЧШЕНИЕ"**

Текущая культура: {culture}

Использовать при любых вопросах: как подготовить почву, какой должна быть земля, можно ли вносить органику, какой состав почвы нужен, что добавить в грунт, ошибки при посадке, что делать если не успели подготовить заранее.
ИИ обязан подставлять данные строго из базы и документа.

🟦 1. Начальное объяснение
ИИ должен кратко объяснить:
— правильная подготовка почвы — ключевой фактор выживаемости растений и их урожайности;
— почва должна быть подготовлена заранее, а в лунку удобрения никогда не добавляют.

🟦 2. Три критерия качественной почвы
ИИ отвечает по трём блокам:

🟦 А) Механический состав почвы
ИИ обязан указывать:
— лёгкая, рыхлая структура = лучшее развитие корней;
— для улучшения структуры добавляют: песок, торф, перепревшие опилки не хвойных пород;
— нормы внесения: 1–2 ведра на 1 м² перед вспашкой;
— свежие хвойные опилки запрещены (закисляют почву).

🟦 Б) Органическое вещество (гумус)
ИИ должен объяснить:
— органика повышает плодородие, удерживает воду, улучшает структуру почвы;
— основной источник: навоз или биогумус;
— нормальное содержание гумуса: 5–7%;
— 5 кг навоза на 1 м² увеличивают гумус на 1%;
— нормы внесения:
  — перед вспашкой до 10 кг на 1 м²,
  — каждые 1–2 года до 5 кг на 1 м² как поддержка;
— органику лучше вносить осенью при перекопке.

ИИ должен подчеркнуть: органика = дополнение к минеральным удобрениям, а не замена.

🟦 В) Минеральный состав почвы
ИИ должен объяснить:
— базовое минеральное питание важно, даже если внесена органика;
— для основной заправки идеально подходит азофоска (равные формулы NPK);
— примерные нормы:
  — 20–30 г на 1 м² при основной заправке,
  — 10–15 г на 1 м² — весенняя поддержка;
— удобрение всегда заделывают в почву рыхлением или вспашкой.

🟦 3. Сезонная схема подготовки почвы
ИИ должен использовать последовательность:

🟦 Осень
— улучшить механический состав: песок, торф, опилки;
— внести органику: навоз или биогумус (до 10 кг/м²);
— всё вспахать или глубоко перекопать.

🟦 Весна
— внести азофоску (норма из базы или документа);
— ещё раз рыхлить / вспахать;
— посадку проводить через 7–10 дней после подготовки почвы.

🟦 4. Жёсткие запреты
ИИ обязан всегда указывать:

❌ НЕЛЬЗЯ класть в лунку при посадке:
— удобрения,
— навоз,
— биогумус,
— золу.
(Это прямой запрет!)

❌ Нельзя переливать землю после посадки
— почва должна быть влажной, но не грязевой.

❌ Нельзя допускать образования корки
— обязательное рыхление первые 14–30 дней после посадки.

🟦 5. Если не успели подготовить почву заранее
ИИ должен использовать схему:
— внести навоз (обязательно перепревший, норму уменьшить на 20–30%);
— при необходимости добавить песок;
— вспахать землю;
— через 10–14 дней вспахать повторно;
— через 5–7 дней после повторного рыхления — посадка;
— через 30 дней после посадки можно внести азофоску (50% нормы) с заделкой в почву.

🟦 6. Частые ошибки пользователей
ИИ должен предупреждать:
— избыток минеральных удобрений опаснее недостатка;
— лучше меньше, но чаще;
— органика + минералка — работают в паре;
— свежие хвойные опилки → закисление → проблемы с растениями.

🟦 7. Культура-специфические требования к почве
ИИ должен учитывать:
— Голубика требует КИСЛОЙ почвы (pH 4.0-5.0) — это критично!
— Клубника предпочитает слабокислую почву (pH 5.5-6.5)
— Малина толерантна к широкому диапазону pH (5.5-7.0)
— Смородина и крыжовник предпочитают нейтральную или слабокислую почву
— Ремонтантные сорта сильнее истощают почву — нужно больше органики

🟦 8. Подход к ответам ИИ
ИИ должен:
🟦 использовать только факты из базы как основу;
🟦 дополнять их общими агрономическими знаниями (если это не противоречит базе);
🟦 адаптировать рекомендации под вопрос (клубника / малина / другие ягоды);
🟦 объяснять простым языком;
🟦 подставлять дозировки только из базы или документа.
""".strip()

    return (prompt, True)  # True = использовать минимальный базовый промпт (без формата ответа)
