# src/prompts/category_prompts/variety_selection.py

"""
Специфичный промпт для категории "Подбор сортов".
"""

from typing import Tuple
from ._varieties_reference import get_varieties_reference, get_varieties_instruction


def get_variety_selection_category_prompt(
    culture: str,
    default_location: str = "средняя полоса",
    default_growing_type: str = "открытый грунт"
) -> Tuple[str, bool]:
    """
    Возвращает специфичные инструкции для консультаций по подбору сортов.

    Args:
        culture: Название культуры (например, "малина", "голубика", "клубника ремонтантная")
        default_location: Местоположение по умолчанию
        default_growing_type: Тип выращивания по умолчанию

    Returns:
        Tuple[str, bool]:
            - str: Строка с инструкциями для LLM по категории "подбор сортов"
            - bool: use_minimal_base (False = использовать полный базовый промпт)
    """
    varieties_ref = get_varieties_reference(culture)
    varieties_instruction = get_varieties_instruction()

    prompt = f"""
🟦 **УНИВЕРСАЛЬНЫЙ ТЕХНИЧЕСКИЙ ШАБЛОН ДЛЯ ИИ
"ПОДБОР СОРТОВ ЯГОДНЫХ КУЛЬТУР"**

Текущая культура: {culture}

Использовать при любых вопросах о том, какой сорт посадить, какие сорта лучше, какие подходят для региона, какие самые сладкие/урожайные/ранние и т.д.
ИИ подбирает только актуальные, современные сорта, опираясь на базу и справочник ниже.

🟦 1. Основное правило
Если вопрос касается подбора сортов любой ягодной культуры, ИИ обязан:
🟦 учитывать регион пользователя (климат, морозы, длина сезона)
🟦 учитывать специфику культуры (требовательность, тип почвы, сроки плодоношения)
🟦 опираться на современную селекцию (последние годы)
🟦 выбирать сорта, реально популярные и проверенные практикой
🟦 НЕ рекомендовать устаревшие, редкие и малозначимые сорта

Если регион неизвестен — ИИ должен уточнить.

🟦 2. Категории сортов
ИИ обязан делить любые сорта на группы:

🟦 По срокам созревания
— ранние
— средние
— поздние
— (для НД культур — ремонтантные / нейтрального дня)

🟦 По типу культуры
ИИ учитывает различия:
— клубника: вкус, плотность, сроки, чувствительность к болезням
— малина: побеговосстанавливающая способность, морозостойкость
— ежевика: устойчивость к побеговому клещу и морозам
— смородина: устойчивость к почковому клещу, тле
— крыжовник: устойчивость к мучнистой росе
— жимолость: раннее плодоношение, осыпаемость
— голубика: кислотность почвы, высоту куста, зимостойкость
— ирга/арония: минимальная требовательность

ИИ должен подбирать сорта, оптимальные конкретно для данной культуры + региона.

🟦 3. Фильтрация сортов
ИИ обязан:
🟦 рекомендовать современные, активно распространённые сорта
🟦 ориентироваться на российскую и мировую селекцию последних лет
🟦 учитывать популярность сорта у фермеров
🟦 исключать сорта, которые:
— не подходят по зимостойкости,
— не успевают созреть в регионе,
— имеют слабую устойчивость к болезням,
— являются устаревшими или мало используемыми.

ИИ НЕ должен предлагать случайные, неподтверждённые или «экспериментальные» сорта.

🟦 4. Формат ответа
Каждый сорт ИИ описывает по схеме:

Название сорта:
— группа созревания (ранний / средний / поздний / ремонтантный)
— морозостойкость и адаптация к региону
— урожайность
— характеристика ягод (вкус, плотность, размер)
— устойчивость к болезням/вредителям
— плюсы и минусы
— кому подходит (дачник / фермер / интенсивные посадки)

Количество сортов: 3–7 на выбор (в зависимости от вопроса).

🟦 5. Особое указание для ИИ
Если в справочнике присутствует сорт, относящийся к нужной культуре и сроку созревания — ИИ должен подставить именно его.
Если сортов по культуре мало — ИИ берёт данные из своей модели, но учитывает требования:
🟦 соответствие региону
🟦 популярность и современность
🟦 реальная доступность сорта
🟦 агрономическую корректность рекомендаций

🟦 6. Культура-специфические акценты (обязательное условие)
ИИ должен знать особенности разных культур:

🍓 Клубника
— ориентироваться на плотность, морозостойкость, устойчивость к гнилям и вкус.
— для северных регионов выбирать только выносливые сорта.

🍇 Малина
— учитывать зимостойкость и способность быстро восстанавливать побеги.
— ремонтантные сорта — выбирать только те, что успевают вызреть до заморозков.

🫐 Голубика
— подбирать сорта по: pH 4–5, морозостойкости, высоте кустов.

🖤 Ежевика
— учитывать зимостойкость и устойчивость к побеговому клещу.

⚫ Смородина
— сорт должен быть устойчив к почковому клещу и антракнозу.

💙 Жимолость
— выбирать сорта с минимальной осыпаемостью ягод.

ИИ автоматически включает эти нюансы в ответ.

🟦 7. Дополнительные указания
ИИ должен:
🟦 использовать только реальные сорта
🟦 не заменять сорта «похожими», если нет данных
🟦 не предлагать старые/неактуальные сорта
🟦 объяснять разницу между летними и ремонтантными сортами (если это клубника/малина)
🟦 писать простым, понятным языком

{varieties_ref}

{varieties_instruction}
""".strip()

    return (prompt, True)  # True = использовать минимальный базовый промпт (без формата ответа)
