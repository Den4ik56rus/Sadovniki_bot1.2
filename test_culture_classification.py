async def run_tests():
    """Запускает все тесты и выводит результаты."""

    print("="*80)
    print("ТЕСТИРОВАНИЕ АВТООПРЕДЕЛЕНИЯ КУЛЬТУРЫ")
    print("="*80)
    print()

    # Инициализируем пул БД
    await init_db_pool()

    total = len(TEST_CASES)
    passed = 0
    failed = 0
    errors_list = []

    for i, (text, expected) in enumerate(TEST_CASES, 1):
        try:
            # detect_culture_name возвращает tuple (culture, cost_usd, tokens)
            result_tuple = await detect_culture_name(text)
            result = result_tuple[0] if isinstance(result_tuple, tuple) else result_tuple

            # Проверяем результат
            is_correct = result == expected

            if is_correct:
                status = "✅ PASS"
                passed += 1
            else:
                status = "❌ FAIL"
                failed += 1
                errors_list.append({
                    "text": text,
                    "expected": expected,
                    "got": result,
                })

            print(f"[{i}/{total}] {status}")
            print(f"  Вопрос: {text}")
            print(f"  Ожидалось: {expected}")
            print(f"  Получено: {result}")
            print()

        except Exception as e:
            status = "💥 ERROR"
            failed += 1
            errors_list.append({
                "text": text,
                "expected": expected,
                "error": str(e),
            })
            print(f"[{i}/{total}] {status}")
            print(f"  Вопрос: {text}")
            print(f"  Ошибка: {e}")
            print()

    # Закрываем пул БД
    await close_db_pool()

    # Итоги
    print("="*80)
    print("РЕЗУЛЬТАТЫ ТЕСТИРОВАНИЯ")
    print("="*80)
    print(f"Всего тестов: {total}")
    print(f"Успешно: {passed} ({passed*100//total}%)")
    print(f"Провалено: {failed} ({failed*100//total}%)")
    print()

    if errors_list:
        print("="*80)
        print("ОШИБКИ КЛАССИФИКАЦИИ")
        print("="*80)
        for i, error in enumerate(errors_list, 1):
            print(f"\n{i}. Вопрос: {error['text']}")
            print(f"   Ожидалось: {error['expected']}")
            if "got" in error:
                print(f"   Получено: {error['got']}")
            if "error" in error:
                print(f"   Ошибка: {error['error']}")
        print()

    return passed, failed


if __name__ == "__main__":
    passed, failed = asyncio.run(run_tests())

    # Возвращаем код выхода (0 = успех, 1 = есть ошибки)
    sys.exit(0 if failed == 0 else 1)
